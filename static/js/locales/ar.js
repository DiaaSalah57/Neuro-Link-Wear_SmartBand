/**
 * NeuroLink Wear — Arabic (ar) locale for the dashboard UI.
 *
 * The app is written as plain-English template strings with no build step, so
 * the Arabic locale is expressed as:
 *   • `exact` — normalised English source text → Arabic (whole text nodes,
 *     placeholders, titles, aria-labels and option labels).
 *   • `rules` — regular expressions for text that contains live values
 *     (numbers, names, timestamps, sensor readings).
 *
 * Keys must be written with single spaces (the i18n engine collapses runs of
 * whitespace before matching, so multi-line template strings still match).
 *
 * Note: clinical narratives generated by the backend (AI explanations, summary
 * bodies) are produced in English at detection time and are stored in the
 * database; this locale translates the UI chrome, alert titles/types and the
 * seeded summaries' titles/tags. See README → Language & accessibility.
 */

/* Arabic-friendly counting: 1 / 2 / 3–10 / 11+ */
const qty = (n, one, two, few, many) => {
  const k = Math.abs(n) % 100;
  if (n === 1) return one;
  if (n === 2) return two;
  if (k >= 3 && k <= 10) return `${n} ${few}`;
  return `${n} ${many}`;
};

/** Relative-time phrasing shared by the standalone rules and composite ones. */
const rel = (s) => {
  const t = String(s).trim();
  if (t === 'just now') return 'الآن';
  let m;
  if ((m = /^(\d+)s ago$/.exec(t))) return `منذ ${qty(+m[1], 'ثانية واحدة', 'ثانيتين', 'ثوانٍ', 'ثانية')}`;
  if ((m = /^(\d+)m ago$/.exec(t))) return `منذ ${qty(+m[1], 'دقيقة واحدة', 'دقيقتين', 'دقائق', 'دقيقة')}`;
  if ((m = /^(\d+)h ago$/.exec(t))) return `منذ ${qty(+m[1], 'ساعة واحدة', 'ساعتين', 'ساعات', 'ساعة')}`;
  if ((m = /^(\d+)d ago$/.exec(t))) return `منذ ${qty(+m[1], 'يوم واحد', 'يومين', 'أيام', 'يومًا')}`;
  return t;
};

